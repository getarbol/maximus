/**
 * maximusProject(), the Vite plugin: it prepares the project when Vite resolves its configuration and before
 * every build, watches the discovered modules and the convention directories, and in development turns a
 * change to a project module into nothing, a full reload or a server restart.
 */
import { mkdirSync, mkdtempSync, readFileSync, rmSync, unlinkSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';

import { afterEach, expect, test, vi } from 'vite-plus/test';

import { maximusProject } from '../../src/tooling/vite.ts';
import type { ProjectOptions } from '../../src/tooling/vite.ts';

type Plugin = ReturnType<typeof maximusProject>;

const CWD = process.cwd();
const directories: string[] = [];

afterEach(() => {
  process.chdir(CWD);
  for (const root of directories.splice(0)) {
    rmSync(root, { recursive: true, force: true });
  }
});

/** A project in a temporary directory, with these files. */
function project(files: Record<string, string>): string {
  const root = mkdtempSync(join(tmpdir(), 'maximus-vite-'));
  directories.push(root);
  write(root, files);
  return root;
}

/** Creates or replaces files of a project. */
function write(root: string, files: Record<string, string>): void {
  for (const [name, contents] of Object.entries(files)) {
    mkdirSync(dirname(join(root, name)), { recursive: true });
    writeFileSync(join(root, name), contents);
  }
}

/** A generated module as text. */
function generated(root: string, name: string): string {
  return readFileSync(join(root, '.maximus', name), 'utf-8');
}

/** A project configured by 7.4's maximus.config.ts, with one route. */
const CONFIGURED = {
  'maximus.config.ts': 'export default {};',
  'routes/v1/notes.ts': 'export const GET = {};',
};

/** What a vite.config.ts states for a tasks service, as the plugin's options source returns it. */
const options: ProjectOptions = {
  application: {
    name: 'tasks',
    namespace: 'tasks',
    title: 'Tasks',
    version: '1.0.0',
    origin: 'https://tasks.example.test',
    tokens: { issuer: 'https://issuer.example.test/', audience: 'https://tasks.example.test' },
    rpc: { callers: [] },
  },
  worker: { http: { basePath: '/api', healthPath: '/health' } },
  env: { production: {}, development: {} },
};

/** Runs the config hook as Vite does when it resolves the configuration. */
function configure(plugin: Plugin, config: { root?: string }, mode = 'development'): void {
  const hook = plugin.config;
  if (typeof hook !== 'function') {
    throw new TypeError('maximusProject() has no config hook');
  }
  void hook.call({} as never, config, { mode, command: 'serve' });
}

/** Runs buildStart and answers the files it asked Vite to watch, sorted. */
function buildStart(plugin: Plugin): string[] {
  const hook = plugin.buildStart;
  if (typeof hook !== 'function') {
    throw new TypeError('maximusProject() has no buildStart hook');
  }
  const watched: string[] = [];
  void hook.call({ addWatchFile: (file: string) => watched.push(file) } as never, {} as never);
  return watched.toSorted();
}

/** Sends one file event through hotUpdate: what the hook answered, and what it asked of the server and client. */
async function hotUpdate(plugin: Plugin, file: string) {
  const hook = plugin.hotUpdate;
  if (!hook || typeof hook !== 'object') {
    throw new TypeError('maximusProject() has no ordered hotUpdate hook');
  }
  const restart = vi.fn(async () => undefined);
  const send = vi.fn();
  const answer = await hook.handler.call(
    { environment: { hot: { send } } } as never,
    {
      file,
      server: { restart },
    } as never
  );
  return { answer, restarts: restart.mock.calls.length, sent: send.mock.calls.map(([payload]) => payload) };
}

test('resolving the configuration prepares its root for its mode, with the options it derives there', () => {
  const root = project({ 'routes/v1/tasks.get.ts': 'export default defineHandler({});' });
  const source = vi.fn(() => options);
  const plugin = maximusProject(source);
  expect(plugin).toMatchObject({ name: 'maximus-project', enforce: 'pre' });
  configure(plugin, { root }, 'development');
  expect(source).toHaveBeenCalledWith(root, 'development');
  expect(generated(root, 'app.ts')).toContain('// Generated by maximus prepare (development).');
  expect(generated(root, 'config.ts')).toContain('"origin":"https://tasks.example.test"');
});

test('without a root, the plugin prepares the directory Vite was started in', () => {
  const root = project(CONFIGURED);
  process.chdir(root);
  const plugin = maximusProject();
  configure(plugin, {}, 'production');
  expect(generated(root, 'app.ts')).toContain('routes_0.GET("/v1/notes", "GET")');
});

test('its api prepares any root for a mode as a build would', () => {
  const root = project({ 'routes/v1/tasks.get.ts': 'export default defineHandler({});' });
  const source = vi.fn(() => options);
  expect(maximusProject(source).api.prepare(root, 'production')).toMatchObject({
    directory: root,
    mode: 'production',
    layout: 'options',
  });
  expect(source).toHaveBeenCalledWith(root, 'production');
  const configured = project(CONFIGURED);
  expect(maximusProject().api.prepare(configured, 'development')).toMatchObject({ layout: 'config' });
});

test('a build watches the discovered modules, the configuration module and the convention directories', () => {
  const root = project({ ...CONFIGURED, 'middleware/10-policy.ts': 'export default {};' });
  const plugin = maximusProject();
  configure(plugin, { root }, 'production');
  // Never the root itself: it holds the generated output, which would loop in build --watch.
  expect(buildStart(plugin)).toEqual([
    join(root, 'maximus.config.ts'),
    join(root, 'middleware'),
    join(root, 'middleware/10-policy.ts'),
    join(root, 'routes'),
    join(root, 'routes/v1/notes.ts'),
  ]);
  const unconfigured = project({ 'routes/v1/tasks.get.ts': 'export default defineHandler({});' });
  const optioned = maximusProject(() => options);
  configure(optioned, { root: unconfigured });
  expect(buildStart(optioned)).toEqual([
    join(unconfigured, 'routes'),
    join(unconfigured, 'routes/v1/tasks.get.ts'),
  ]);
});

test('only a convention directory, a root module or a 7.3 entry rediscovers the project', async () => {
  const root = project({
    'src/application.ts': 'export const base = {};',
    'src/worker.ts': 'export const options = {};',
  });
  // The legacy layout configures itself, so the source derives nothing; each call is one rediscovery.
  const source = vi.fn(() => undefined);
  const plugin = maximusProject(source);
  configure(plugin, { root });
  const rediscovered = async (file: string) => {
    const before = source.mock.calls.length;
    const { answer, restarts, sent } = await hotUpdate(plugin, join(root, file));
    expect({ answer, restarts, sent }, file).toEqual({ answer: undefined, restarts: 0, sent: [] });
    return source.mock.calls.length > before;
  };
  for (const file of [
    'routes/v1/notes.get.ts',
    'mcp/tools/summarize.ts',
    'pages/index.ts',
    'middleware/10-policy.ts',
    'crons/daily.ts',
    'queues/jobs.ts',
    'email/help@example.test.ts',
    'durable-objects/store.ts',
    'maximus.config.mjs',
    'errors.ts',
    'auth.mts',
    'context.js',
    'src/application.ts',
    'src/worker.ts',
  ]) {
    expect(await rediscovered(file), file).toBe(true);
  }
  for (const file of [
    'README.md',
    'vite.config.ts',
    'errors.tsx',
    'lib/errors.ts',
    'src/tasks.ts',
    'src',
    'tests/notes.test.ts',
    '.maximus/app.ts',
    '../elsewhere/routes/v1/notes.get.ts',
  ]) {
    expect(await rediscovered(file), file).toBe(false);
  }
});

test('a body edit lets Vite update the module, and a new or deleted route reloads the page', async () => {
  const root = project(CONFIGURED);
  const plugin = maximusProject();
  configure(plugin, { root });
  write(root, { 'routes/v1/notes.ts': 'const notes = {};\nexport const GET = notes;' });
  expect(await hotUpdate(plugin, join(root, 'routes/v1/notes.ts'))).toEqual({
    answer: undefined,
    restarts: 0,
    sent: [],
  });
  write(root, { 'routes/v1/tags.ts': 'export const GET = {};' });
  expect(await hotUpdate(plugin, join(root, 'routes/v1/tags.ts'))).toEqual({
    answer: undefined,
    restarts: 0,
    sent: [{ type: 'full-reload' }],
  });
  expect(generated(root, 'app.ts')).toContain('"/v1/tags"');
  unlinkSync(join(root, 'routes/v1/tags.ts'));
  expect((await hotUpdate(plugin, join(root, 'routes/v1/tags.ts'))).sent).toEqual([{ type: 'full-reload' }]);
  expect(generated(root, 'app.ts')).not.toContain('"/v1/tags"');
});

test('a new or removed Durable Object restarts the server so Cloudflare refreshes the Worker exports', async () => {
  const root = project(CONFIGURED);
  const plugin = maximusProject();
  configure(plugin, { root });
  write(root, { 'durable-objects/session-store.ts': 'export default class SessionStore {}' });
  // An empty answer: no module is updated, as the restarted server loads the new entry.
  expect(await hotUpdate(plugin, join(root, 'durable-objects/session-store.ts'))).toEqual({
    answer: [],
    restarts: 1,
    sent: [],
  });
  write(root, { 'durable-objects/session-store.ts': 'export default class SessionStore { size = 0; }' });
  expect((await hotUpdate(plugin, join(root, 'durable-objects/session-store.ts'))).restarts).toBe(0);
  unlinkSync(join(root, 'durable-objects/session-store.ts'));
  expect((await hotUpdate(plugin, join(root, 'durable-objects/session-store.ts'))).restarts).toBe(1);
});

test('a new configuration module restarts the server', async () => {
  const root = project({
    'src/application.ts': 'export const base = {};',
    'src/worker.ts': 'export const options = {};',
  });
  const plugin = maximusProject();
  configure(plugin, { root });
  write(root, { 'maximus.config.ts': 'export default {};' });
  expect(await hotUpdate(plugin, join(root, 'maximus.config.ts'))).toMatchObject({ answer: [], restarts: 1 });
  expect(generated(root, 'base.ts')).toContain("import config from '../maximus.config.ts';");
});

test('a discovery failure is thrown to Vite and keeps the previous graph until the project is fixed', async () => {
  const root = project(CONFIGURED);
  const plugin = maximusProject();
  configure(plugin, { root });
  const app = generated(root, 'app.ts');
  write(root, { 'routes/v1/notes/index.ts': 'export const POST = {};' });
  await expect(hotUpdate(plugin, join(root, 'routes/v1/notes/index.ts'))).rejects.toThrow(
    'Multiple route files claim /v1/notes'
  );
  expect(generated(root, 'app.ts')).toBe(app);
  rmSync(join(root, 'routes/v1/notes'), { recursive: true });
  write(root, { 'routes/v1/notes.ts': 'export const GET = {}; export const POST = {};' });
  expect((await hotUpdate(plugin, join(root, 'routes/v1/notes.ts'))).sent).toEqual([{ type: 'full-reload' }]);
  expect(generated(root, 'app.ts')).toContain('routes_0.POST("/v1/notes", "POST")');
});
