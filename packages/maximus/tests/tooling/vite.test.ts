/**
 * maximusProject(), the Vite plugin: it prepares the project when Vite resolves its configuration and before
 * every build, watches the discovered modules and the convention directories, and in development turns a
 * change to a project module into nothing, a full reload or a server restart.
 */
import { existsSync, rmSync, unlinkSync } from 'node:fs';
import { join } from 'node:path';

import { afterEach, expect, test, vi } from 'vite-plus/test';

import { maximusProject } from '../../src/tooling/vite.ts';
import { generated, options, project, removeProjects, ROUTE, write } from './fixtures.ts';

type Plugin = ReturnType<typeof maximusProject>;

const CWD = process.cwd();

afterEach(() => {
  process.chdir(CWD);
  removeProjects();
});

/** Runs the config hook as Vite does when it resolves the configuration. */
function configure(plugin: Plugin, config: { root?: string }, mode = 'development'): void {
  const hook = plugin.config;
  if (typeof hook !== 'function') {
    throw new TypeError('maximusProject() has no config hook');
  }
  void hook.call({} as never, config, { mode, command: 'serve' });
}

/** Runs buildStart and answers the files it asked Vite to watch, sorted. */
function buildStart(plugin: Plugin): string[] {
  const hook = plugin.buildStart;
  if (typeof hook !== 'function') {
    throw new TypeError('maximusProject() has no buildStart hook');
  }
  const watched: string[] = [];
  void hook.call({ addWatchFile: (file: string) => watched.push(file) } as never, {} as never);
  return watched.toSorted();
}

/** Sends one file event through hotUpdate: what the hook answered, and what it asked of the server and client. */
async function hotUpdate(plugin: Plugin, file: string) {
  const hook = plugin.hotUpdate;
  if (!hook || typeof hook !== 'object') {
    throw new TypeError('maximusProject() has no ordered hotUpdate hook');
  }
  const restart = vi.fn(async () => undefined);
  const send = vi.fn();
  const answer = await hook.handler.call(
    { environment: { hot: { send } } } as never,
    {
      file,
      server: { restart },
    } as never
  );
  return { answer, restarts: restart.mock.calls.length, sent: send.mock.calls.map(([payload]) => payload) };
}

/** The plugin with the options of a tasks service. */
function tasksPlugin(): Plugin {
  return maximusProject(() => options());
}

test('resolving the configuration prepares its root for its mode, with the options it derives there', () => {
  const root = project({ 'routes/v1/tasks.get.ts': ROUTE });
  const source = vi.fn(() => options());
  const configured = maximusProject(source);
  expect(configured).toMatchObject({ name: 'maximus-project', enforce: 'pre' });
  configure(configured, { root }, 'development');
  expect(source).toHaveBeenCalledWith(root, 'development');
  expect(generated(root, 'app.ts')).toContain('// Generated by maximus prepare (development).');
  expect(generated(root, 'config.ts')).toContain('"origin":"https://tasks.example.test"');
});

test('without a root, the plugin prepares the directory Vite was started in', () => {
  const root = project({ 'routes/v1/notes.get.ts': ROUTE });
  process.chdir(root);
  configure(tasksPlugin(), {}, 'production');
  expect(generated(root, 'app.ts')).toContain('bindRoute(base, route_0, "/v1/notes", "GET")');
});

test('its api prepares any root for a mode as a build would', () => {
  const root = project({ 'routes/v1/tasks.get.ts': ROUTE });
  const source = vi.fn(() => options());
  expect(maximusProject(source).api.prepare(root, 'production')).toMatchObject({
    directory: root,
    mode: 'production',
    modules: { routes: 1 },
  });
  expect(source).toHaveBeenCalledWith(root, 'production');
});

test('a build watches the discovered modules and the convention directories, never the root', () => {
  const root = project({ 'routes/v1/notes.get.ts': ROUTE, 'middleware/10-policy.ts': 'export default {};' });
  const configured = tasksPlugin();
  configure(configured, { root }, 'production');
  // Never the root itself: it holds the generated output, which would loop in build --watch.
  expect(buildStart(configured)).toEqual([
    join(root, 'middleware'),
    join(root, 'middleware/10-policy.ts'),
    join(root, 'routes'),
    join(root, 'routes/v1/notes.get.ts'),
  ]);
});

test('only a convention directory or a root module rediscovers the project', async () => {
  const root = project({});
  // Each call of the source is one rediscovery.
  const source = vi.fn(() => options());
  const configured = maximusProject(source);
  configure(configured, { root });
  const rediscovered = async (file: string) => {
    const before = source.mock.calls.length;
    const { answer, restarts, sent } = await hotUpdate(configured, join(root, file));
    expect({ answer, restarts, sent }, file).toEqual({ answer: undefined, restarts: 0, sent: [] });
    return source.mock.calls.length > before;
  };
  for (const file of [
    'routes/v1/notes.get.ts',
    'mcp/tools/summarize.ts',
    'pages/index.ts',
    'middleware/10-policy.ts',
    'crons/daily.ts',
    'queues/jobs.ts',
    'email/help@example.test.ts',
    'durable-objects/store.ts',
    'errors.ts',
    'auth.mts',
    'context.js',
  ]) {
    expect(await rediscovered(file), file).toBe(true);
  }
  for (const file of [
    'README.md',
    'vite.config.ts',
    'errors.tsx',
    'lib/errors.ts',
    'src/tasks.ts',
    'src',
    'tests/notes.test.ts',
    '.maximus/app.ts',
    '../elsewhere/routes/v1/notes.get.ts',
  ]) {
    expect(await rediscovered(file), file).toBe(false);
  }
});

test('a body edit lets Vite update the module, and a new or deleted route reloads the page', async () => {
  const root = project({ 'routes/v1/notes.get.ts': ROUTE });
  const configured = tasksPlugin();
  configure(configured, { root });
  write(root, { 'routes/v1/notes.get.ts': `const notes = {};\n${ROUTE}` });
  expect(await hotUpdate(configured, join(root, 'routes/v1/notes.get.ts'))).toEqual({
    answer: undefined,
    restarts: 0,
    sent: [],
  });
  write(root, { 'routes/v1/tags.get.ts': ROUTE });
  expect(await hotUpdate(configured, join(root, 'routes/v1/tags.get.ts'))).toEqual({
    answer: undefined,
    restarts: 0,
    sent: [{ type: 'full-reload' }],
  });
  expect(generated(root, 'app.ts')).toContain('"/v1/tags"');
  unlinkSync(join(root, 'routes/v1/tags.get.ts'));
  expect((await hotUpdate(configured, join(root, 'routes/v1/tags.get.ts'))).sent).toEqual([
    { type: 'full-reload' },
  ]);
  expect(generated(root, 'app.ts')).not.toContain('"/v1/tags"');
});

test('a new or removed Durable Object restarts the server so Cloudflare refreshes the Worker exports', async () => {
  const root = project({ 'routes/v1/notes.get.ts': ROUTE });
  const configured = tasksPlugin();
  configure(configured, { root });
  write(root, { 'durable-objects/session-store.ts': 'export default class SessionStore {}' });
  // An empty answer: no module is updated, as the restarted server loads the new entry.
  expect(await hotUpdate(configured, join(root, 'durable-objects/session-store.ts'))).toEqual({
    answer: [],
    restarts: 1,
    sent: [],
  });
  write(root, { 'durable-objects/session-store.ts': 'export default class SessionStore { size = 0; }' });
  expect((await hotUpdate(configured, join(root, 'durable-objects/session-store.ts'))).restarts).toBe(0);
  unlinkSync(join(root, 'durable-objects/session-store.ts'));
  expect((await hotUpdate(configured, join(root, 'durable-objects/session-store.ts'))).restarts).toBe(1);
});

test('a discovery failure is thrown to Vite and keeps the previous graph until the project is fixed', async () => {
  const root = project({ 'routes/v1/notes.get.ts': ROUTE });
  const configured = tasksPlugin();
  configure(configured, { root });
  const app = generated(root, 'app.ts');
  write(root, { 'routes/v1/notes/index.get.ts': ROUTE });
  await expect(hotUpdate(configured, join(root, 'routes/v1/notes/index.get.ts'))).rejects.toThrow(
    'Multiple route files claim GET /v1/notes'
  );
  expect(generated(root, 'app.ts')).toBe(app);
  rmSync(join(root, 'routes/v1/notes'), { recursive: true });
  write(root, { 'routes/v1/notes.post.ts': ROUTE });
  expect((await hotUpdate(configured, join(root, 'routes/v1/notes.post.ts'))).sent).toEqual([
    { type: 'full-reload' },
  ]);
  expect(generated(root, 'app.ts')).toContain('"/v1/notes", "POST"');
});

test('index.html coming or going restarts the server, and a page coming or going reloads the app', async () => {
  const root = project({ 'routes/v1/tasks.get.ts': ROUTE });
  // What the plugin of vite.config.ts reports: a web app while index.html is at the root.
  const configured = maximusProject((directory) =>
    options({ web: existsSync(join(directory, 'index.html')) })
  );
  configure(configured, { root });
  write(root, { 'index.html': '<!doctype html>' });
  expect(await hotUpdate(configured, join(root, 'index.html'))).toEqual({
    answer: [],
    restarts: 1,
    sent: [],
  });
  const home = 'export default function Home() {\n  return null;\n}\n';
  write(root, { 'app/root.tsx': home, 'app/routes/index.tsx': home, 'public/favicon.svg': '<svg/>' });
  expect(await hotUpdate(configured, join(root, 'app/routes/index.tsx'))).toEqual({
    answer: undefined,
    restarts: 0,
    sent: [{ type: 'full-reload' }],
  });
  expect(buildStart(configured)).toEqual(
    expect.arrayContaining([
      join(root, 'app'),
      join(root, 'app/root.tsx'),
      join(root, 'app/routes/index.tsx'),
      join(root, 'public'),
    ])
  );
  // Editing a page or a public file changes no generated module: Vite updates it as it is.
  write(root, { 'app/routes/index.tsx': home.replace('null', '"home"') });
  expect(await hotUpdate(configured, join(root, 'app/routes/index.tsx'))).toEqual({
    answer: undefined,
    restarts: 0,
    sent: [],
  });
  rmSync(join(root, 'app'), { recursive: true });
  expect((await hotUpdate(configured, join(root, 'app/routes/index.tsx'))).sent).toEqual([
    { type: 'full-reload' },
  ]);
  unlinkSync(join(root, 'index.html'));
  expect((await hotUpdate(configured, join(root, 'index.html'))).restarts).toBe(1);
});
