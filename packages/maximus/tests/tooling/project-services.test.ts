/**
 * The services a project calls over native RPC: `maximus prepare` types each binding from the RPC document
 * its service publishes, in `.maximus/services/`, gives `Env` that type, watches the document, removes the
 * module of a service the project no longer calls, and refuses a document it cannot read.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { afterEach, expect, test } from 'vite-plus/test';

import { createRpcOpenApi, defineErrors, maximus, ok, t } from '../../src/index.ts';
import { generated, options, prepare, project, removeProjects, ROUTE } from './fixtures.ts';

afterEach(removeProjects);

/** The RPC document of a pricing service whose one method quotes items. */
function pricingDocument(): string {
  const app = maximus<Record<string, never>>({
    name: 'pricing',
    namespace: 'pricing',
    title: 'Pricing',
    version: '1',
    origin: 'https://pricing.example.test',
    tokens: { issuer: 'https://issuer.example.test/', audience: 'https://pricing.example.test' },
    errors: defineErrors({}),
    rpc: { callers: ['tasks'] },
    telemetry: { enabled: false },
  })
    .operation(
      'quoteItems',
      {
        title: 'Quote items',
        description: 'Price the items.',
        effect: 'read',
        scope: 'pricing:quotes:read',
        input: t.Object({ count: t.Integer() }, { additionalProperties: false }),
        output: t.Object({ totalCents: t.Integer() }, { $id: 'Quote', additionalProperties: false }),
        failures: [],
        http: { method: 'POST', path: '/v1/quotes' },
        rpc: true,
        actorKinds: ['service'],
      },
      async () => ok({ totalCents: 0 })
    )
    .build();
  return JSON.stringify(createRpcOpenApi(app));
}

/** The tasks project's options, calling pricing through the document at `openapi`. */
function calling(openapi: string) {
  return { ...options(), services: { PRICING: { worker: 'pricing', openapi } } };
}

test("types each service's binding from the RPC document it publishes, and watches the document", () => {
  const root = project({ 'routes/v1/tasks.get.ts': ROUTE, 'contracts/pricing.rpc.json': pricingDocument() });
  const prepared = prepare(root, 'production', calling('contracts/pricing.rpc.json'));
  const service = generated(root, 'services/pricing.ts');
  expect(service).toContain('// Generated by maximus prepare from contracts/pricing.rpc.json.');
  expect(service).toContain(
    '  quoteItems(principal: Principal, input: QuoteItemsInput): Promise<Result<Quote, QuoteItemsFailure>>;'
  );
  const env = generated(root, 'env.d.ts');
  expect(env).toContain(
    'type Services = {\n  "PRICING": Service<import(\'./services/pricing.ts\').PricingService>;\n};'
  );
  expect(env).toContain('interface Env extends Omit<Bindings, keyof Services>, Services {}');
  expect(prepared.files).toContain(join(root, 'contracts/pricing.rpc.json'));
  // A service the project no longer calls leaves no module behind.
  prepare(root, 'production', options());
  expect(existsSync(join(root, '.maximus/services/pricing.ts'))).toBe(false);
  expect(generated(root, 'env.d.ts')).toContain('    interface Env extends Bindings {}');
});

test('a service document that does not exist, or that is not JSON, is refused, and the output kept', () => {
  const root = project({ 'routes/v1/tasks.get.ts': ROUTE });
  prepare(root);
  const before = readFileSync(join(root, '.maximus/env.d.ts'), 'utf-8');
  expect(() => prepare(root, 'production', calling('../pricing/openapi.rpc.json'))).toThrow(
    'services.PRICING: ../pricing/openapi.rpc.json does not exist; write it with maximus openapi in that service.'
  );
  writeFileSync(join(root, 'pricing.json'), '{ "openapi":');
  expect(() => prepare(root, 'production', calling('pricing.json'))).toThrow(
    'services.PRICING: pricing.json is not JSON.'
  );
  expect(readFileSync(join(root, '.maximus/env.d.ts'), 'utf-8')).toBe(before);
});
