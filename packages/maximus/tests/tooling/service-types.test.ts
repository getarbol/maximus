/**
 * The types of another service's native RPC methods, from the document it publishes: the entrypoint with one
 * method per RPC operation, each input, output and failure, every schema shape a document holds, a module of
 * types alone whatever text the document holds, and the documents that cannot type a binding.
 */
import { parseSync } from 'vite';
import { expect, it } from 'vite-plus/test';

import { createRpcOpenApi, defineErrors, maximus, ok, t } from '../../src/index.ts';
import { serviceModule, serviceTypeName } from '../../src/tooling/internal/service-types.ts';

/** The statements of a module that run: none in a module of type imports and type declarations alone. */
function runtimeStatements(module: string): string[] {
  const { program, errors } = parseSync('service.ts', module);
  expect(errors).toEqual([]);
  return program.body
    .filter(
      (statement) =>
        !(statement.type === 'ImportDeclaration' && statement.importKind === 'type') &&
        !(
          statement.type === 'ExportNamedDeclaration' &&
          (statement.declaration?.type === 'TSInterfaceDeclaration' ||
            statement.declaration?.type === 'TSTypeAliasDeclaration')
        )
    )
    .map((statement) => module.slice(statement.start, statement.end));
}

const errors = defineErrors({
  unknownSku: {
    code: 'UNKNOWN_SKU',
    status: 422,
    message: 'An item is not in the catalog.',
    dataSchema: t.Object({ index: t.Integer({ minimum: 0 }) }, { additionalProperties: false }),
  },
});

/** Pricing, whose one RPC method quotes items. */
function pricing() {
  return maximus<Record<string, never>>({
    name: 'pricing',
    namespace: 'pricing',
    title: 'Pricing',
    version: '1',
    origin: 'https://pricing.example.test',
    tokens: { issuer: 'https://issuer.example.test/', audience: 'https://pricing.example.test' },
    errors,
    rpc: { callers: ['orders'] },
    telemetry: { enabled: false },
  })
    .operation(
      'quoteItems',
      {
        title: 'Quote items',
        description: 'Price the items of an order.',
        effect: 'read',
        scope: 'pricing:quotes:read',
        input: t.Object(
          {
            items: t.Array(
              t.Object({ sku: t.String(), quantity: t.Integer() }, { additionalProperties: false })
            ),
          },
          { additionalProperties: false }
        ),
        output: t.Object(
          { currency: t.Literal('USD'), totalCents: t.Integer() },
          { $id: 'Quote', additionalProperties: false }
        ),
        failures: ['UNKNOWN_SKU'],
        http: { method: 'POST', path: '/v1/quotes' },
        visibility: 'internal',
        rpc: true,
        actorKinds: ['user', 'service'],
      },
      async () => ok({ currency: 'USD' as const, totalCents: 0 })
    )
    .build();
}

it("types each RPC method from the service's document: its input, its output and the failures it answers", () => {
  const module = serviceModule('PRICING', createRpcOpenApi(pricing()), '../pricing/openapi.rpc.json');
  expect(module).toContain('// Generated by maximus prepare from ../pricing/openapi.rpc.json.');
  expect(module).toContain("import type { Principal, Result } from '@arbol-ai/maximus';");
  expect(module).toContain('export interface PricingService extends WorkerEntrypoint {');
  expect(module).toContain('  /** Quote items: Price the items of an order. */');
  expect(module).toContain(
    '  quoteItems(principal: Principal, input: QuoteItemsInput): Promise<Result<Quote, QuoteItemsFailure>>;'
  );
  // The input is the document's own component, so no alias repeats it.
  expect(module).not.toContain('export type QuoteItemsInput');
  expect(module).toContain(
    'export interface QuoteItemsInput {\n  items: Array<{\n    sku: string;\n    quantity: number;\n  }>;\n}'
  );
  expect(module).toContain("export interface Quote {\n  currency: 'USD';\n  totalCents: number;\n}");
  // Each failure fixes its code, which a caller narrows on, and the data its code declares.
  expect(module).toContain('export type QuoteItemsFailure =\n  | InvalidInputFailure\n');
  expect(module).toContain("  code: 'UNKNOWN_SKU';");
  expect(module).toContain('  data: UnknownSkuFailureData;');
  expect(module).toContain('export interface UnknownSkuFailureData {\n  index: number;\n}');
  expect(module).toContain('export type Empty = Record<string, never>;');
  expect(runtimeStatements(module)).toEqual([]);
});

/** A document of one RPC method whose input and output hold these schemas, with these components. */
function documentWith(input: object, output: object, schemas: Record<string, unknown> = {}) {
  return {
    openapi: '3.1.0',
    info: { title: 'Shapes', version: '1' },
    paths: {
      '/v1/shapes/{shapeId}': {
        get: {
          operationId: 'getShape',
          'x-native-rpc': true,
          parameters: [
            {
              name: 'shapeId',
              in: 'path',
              required: true,
              description: 'The shape id.',
              schema: { type: 'string' },
            },
            { name: 'fields', in: 'query', required: false, schema: input },
          ],
          responses: {
            200: {
              content: { 'application/json': { schema: { $ref: '#/components/schemas/ShapeResponse' } } },
            },
          },
        },
      },
    },
    components: {
      schemas: {
        ShapeResponse: { type: 'object', properties: { data: output } },
        ...schemas,
      },
    },
  };
}

it('types every schema shape a document holds', () => {
  const output = {
    type: 'object',
    additionalProperties: false,
    required: ['tags', 'kind', 'pair', 'node', 'nullable', 'mixed'],
    properties: {
      tags: { type: 'array', items: { type: 'string' } },
      kind: { enum: ['circle', 'square'] },
      pair: { type: 'array', prefixItems: [{ type: 'number' }, { type: 'boolean' }] },
      node: { $ref: '#/components/schemas/Node' },
      nullable: { anyOf: [{ type: 'string' }, { type: 'null' }] },
      mixed: { type: ['integer', 'null'] },
      'odd-name': {
        description: 'A field whose name is no identifier.',
        allOf: [
          { $ref: '#/components/schemas/Named' },
          { type: 'object', properties: { extra: { const: 1 } } },
        ],
      },
      counts: { type: 'object', patternProperties: { '^[a-z]+$': { type: 'integer' } } },
      joined: {
        allOf: [
          { anyOf: [{ type: 'object', properties: { label: { type: 'string' } } }, { type: 'null' }] },
          { $ref: '#/components/schemas/Named' },
        ],
      },
      anything: {},
      never: false,
      open: { type: 'object' },
    },
  };
  const module = serviceModule(
    'SHAPES_API',
    documentWith({ type: 'string' }, output, {
      // A component that refers to itself names its own type.
      Node: {
        type: 'object',
        required: ['children'],
        properties: { children: { type: 'array', items: { $ref: '#/components/schemas/Node' } } },
      },
      Named: { description: 'A "named" */ thing.', type: 'object', properties: { name: { type: 'string' } } },
    }),
    'shapes.json'
  );
  expect(serviceTypeName('SHAPES_API')).toBe('ShapesApi');
  expect(module).toContain('export interface ShapesApiService extends WorkerEntrypoint {');
  // An output the document does not name is the method's own alias, which the signature reads.
  expect(module).toContain(
    '  getShape(principal: Principal, input: GetShapeInput): Promise<Result<GetShapeOutput, GetShapeFailure>>;'
  );
  expect(module).toContain('export type GetShapeOutput = {\n  tags: string[];');
  // Path and query parameters join into the one input the method takes, each described.
  expect(module).toContain(
    'export type GetShapeInput = {\n  /** The shape id. */\n  shapeId: string;\n  fields?: string;\n};'
  );
  for (const line of [
    '  tags: string[];',
    "  kind: 'circle' | 'square';",
    '  pair: [number, boolean];',
    '  node: Node;',
    '  nullable: string | null;',
    '  mixed: number | null;',
    '  /** A field whose name is no identifier. */',
    "  'odd-name'?: Named & {\n    extra?: 1;\n  };",
    '  counts?: {\n    [key: string]: number;\n  };',
    // A union joined with another type keeps its members together.
    '  joined?: ({\n    label?: string;\n  } | null) & Named;',
    '  anything?: unknown;',
    '  never?: never;',
    '  open?: {\n    [key: string]: unknown;\n  };',
    'export interface Node {\n  children: Node[];\n}',
    '/** A "named" * / thing. */',
  ]) {
    expect(module).toContain(line);
  }
  // A method that answers no failure its document names has none to narrow.
  expect(module).toContain('export type GetShapeFailure = never;');
  expect(runtimeStatements(module)).toEqual([]);
});

it('keeps every text of the document inside the comment or the literal that holds it', () => {
  const text = '*/ export const leaked = 1; /* \' " \\ \n export const next = 2;\r\u2028';
  const document = documentWith(
    { enum: [text] },
    {
      type: 'object',
      required: [text],
      properties: { [text]: { description: text, const: text } },
    }
  );
  const module = serviceModule(
    'SHAPES',
    { ...document, info: { title: text, version: '1' } },
    'shapes.json\nexport const source = 3;'
  );
  expect(runtimeStatements(module)).toEqual([]);
  // The text survives as the literal type of the field that holds it.
  expect(module).toContain(
    `  '*/ export const leaked = 1; /* \\' \\" \\\\ \\n export const next = 2;\\r\u2028': '*/ export`
  );
});

it('refuses a document that cannot type a binding, naming the binding and its file', () => {
  const notes = '../notes/openapi.json';
  expect(() => serviceModule('NOTES', { swagger: '2.0', paths: {} }, notes)).toThrow(
    'services.NOTES: ../notes/openapi.json is not an OpenAPI 3.1 document; write it with maximus openapi in that service.'
  );
  expect(() =>
    serviceModule(
      'NOTES',
      { openapi: '3.1.0', paths: { '/v1/notes': { get: { operationId: 'listNotes' } } } },
      notes
    )
  ).toThrow(
    'services.NOTES: ../notes/openapi.json documents no route served over native RPC: declare rpc in the routes this service calls.'
  );
  const named = documentWith(
    { type: 'string' },
    { $ref: '#/components/schemas/GetShapeFailure' },
    {
      GetShapeFailure: { type: 'string' },
    }
  );
  // The component takes the name the method's failures would: the document must rename it.
  const withFailure = {
    ...named,
    paths: {
      '/v1/shapes/{shapeId}': {
        get: {
          ...named.paths['/v1/shapes/{shapeId}'].get,
          responses: {
            ...named.paths['/v1/shapes/{shapeId}'].get.responses,
            404: { content: { 'application/json': { schema: { $ref: '#/components/schemas/ShapeError' } } } },
          },
        },
      },
    },
    components: {
      schemas: {
        ...named.components.schemas,
        ShapeError: { type: 'object', properties: { error: { type: 'number' } } },
      },
    },
  };
  expect(() => serviceModule('SHAPES', withFailure, 'shapes.json')).toThrow(
    'services.SHAPES: shapes.json names GetShapeFailure twice among the types of the binding'
  );
  expect(() =>
    serviceModule(
      'SHAPES',
      documentWith({ type: 'string' }, { $ref: '#/components/schemas/Missing' }),
      'shapes.json'
    )
  ).toThrow('The document refers to the component Missing, which it does not define.');
  expect(() =>
    serviceModule(
      'SHAPES',
      documentWith({ type: 'string' }, { $ref: 'https://example.test/shape.json' }),
      'shapes.json'
    )
  ).toThrow('The document refers to https://example.test/shape.json, outside its component schemas.');
  // The module imports Principal and Result, so no component of the document may take their names.
  expect(() =>
    serviceModule(
      'SHAPES',
      documentWith(
        { type: 'string' },
        { $ref: '#/components/schemas/Principal' },
        { Principal: { type: 'object', properties: { actorId: { type: 'string' } } } }
      ),
      'shapes.json'
    )
  ).toThrow('services.SHAPES: shapes.json names Principal twice among the types of the binding');
  const unnamed = documentWith({ type: 'string' }, { type: 'string' });
  const { get } = unnamed.paths['/v1/shapes/{shapeId}'];
  expect(() =>
    serviceModule(
      'SHAPES',
      { ...unnamed, paths: { '/v1/shapes/{shapeId}': { get: { ...get, operationId: 'Get-Shape' } } } },
      'shapes.json'
    )
  ).toThrow('Every native RPC operation of the document has a camelCase operationId.');
});
