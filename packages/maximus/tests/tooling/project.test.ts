/**
 * `maximus prepare`'s main matrix: routes, tools, pages, middleware, events and Durable Objects discovered
 * from their files without running them; mode suffixes; the modules that complete the application; and the
 * configuration and bindings `vite.config.ts` states, carried by the generated modules.
 */
import { existsSync, symlinkSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { afterEach, expect, test } from 'vite-plus/test';

import { generated, options, prepare, project, removeProjects, ROUTE, write } from './fixtures.ts';

afterEach(removeProjects);

test('discovery creates static typed imports without evaluating modules', () => {
  const root = project({
    'routes/(team)/v1/notes/[noteId].get.ts': `throw new Error("must not execute during discovery"); ${ROUTE}`,
    'pages/index.ts': 'export default {};',
    'middleware/02-second.ts': 'export default {};',
    'middleware/01-first.ts': 'export default {};',
    'durable-objects/session-store.ts': 'export default class SessionStore {}',
  });
  prepare(root);
  expect(generated(root, 'app.ts')).toContain(
    '.mount(bindRoute(base, route_0, "/v1/notes/{noteId}", "GET"))'
  );
  const middleware = generated(root, 'middleware.ts');
  expect(middleware.indexOf('01-first')).toBeLessThan(middleware.indexOf('02-second'));
  expect(middleware).toContain('collectMiddleware([middleware_0, middleware_1] as const)');
  const worker = generated(root, 'worker.ts');
  expect(worker).toContain('pages: { "/": { GET: page_0 } },');
  expect(worker).toContain('export const SessionStore = worker.durableObject(durable_object_0);');
});

test('mode filtering excludes helpers and tests even when a test carries a mode suffix', () => {
  const root = project({
    'routes/v1/live.get.prod.ts': ROUTE,
    'routes/v1/debug.get.dev.ts': ROUTE,
    'routes/v1/hidden.test.prod.ts': '',
    'routes/v1/_helpers.ts': '',
    'routes/v1/types.d.ts': '',
    'email/_default.ts': '',
  });
  expect(prepare(root).modules).toMatchObject({ routes: 1, email: 1 });
  const production = generated(root, 'app.ts');
  expect(production).toContain('live.get.prod.ts');
  expect(production).not.toContain('debug');
  prepare(root, 'development');
  expect(generated(root, 'app.ts')).toContain('debug.get.dev.ts');
  expect(generated(root, 'app.ts')).toContain('// Generated by maximus prepare (development).');
});

test('an email recipient whose domain ends in dev, prod or test keeps it, beside mode-suffixed and test modules', () => {
  const root = project({
    'email/support@company.dev.ts': '',
    'email/ops@team.prod.ts': '',
    'email/help@example.test.ts': '',
    'email/help@example.com.dev.ts': '',
    'email/help@example.com.test.ts': '',
    'email/notes.test.ts': '',
    'email/types.d.ts': '',
  });
  const recipients = (mode: string) => {
    prepare(root, mode);
    return [...generated(root, 'worker.ts').matchAll(/"([^"]+)": email_\d+/g)].map(
      ([, recipient]) => recipient
    );
  };
  expect(recipients('production')).toEqual(['help@example.test', 'ops@team.prod', 'support@company.dev']);
  expect(recipients('development')).toEqual([
    'help@example.com',
    'help@example.test',
    'ops@team.prod',
    'support@company.dev',
  ]);
});

