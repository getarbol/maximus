test("a binding to one of the Worker's own Durable Object classes is typed by that class", () => {
  const schedules = { type: 'durable-object', worker: 'tasks', exportName: 'DaySchedule' };
  const elsewhere = { type: 'durable-object', worker: 'billing', exportName: 'DaySchedule' };
  const configured = options({
    env: {
      production: { SCHEDULES: schedules, LEDGER: elsewhere },
      development: { SCHEDULES: schedules, LEDGER: elsewhere, DEVELOPMENT_TOKEN: { type: 'secret' } },
    },
  });
  const root = project({ 'durable-objects/day-schedule.ts': 'export default class DaySchedule {}' });
  prepare(root, 'development', configured);
  const env = generated(root, 'env.d.ts');
  expect(env).toContain(
    'type DurableObjects = {\n  "SCHEDULES": DurableObjectNamespace<import("../durable-objects/day-schedule.ts").default>;\n};'
  );
  expect(env).toContain('interface Env extends Omit<Bindings, keyof DurableObjects>, DurableObjects {}');
  // Another Worker's class of the same name is not this one: Cloudflare's inference types that binding.
  expect(env).not.toContain('"LEDGER": DurableObjectNamespace');
});

test('the generated modules carry the configuration and infer Env from the bindings of each mode', () => {
  const configured = options({
    env: {
      production: { TASKS: { type: 'kv' } },
      development: { TASKS: { type: 'kv' }, DEVELOPMENT_TOKEN: { type: 'secret' } },
    },
  });
  const root = project({ 'routes/v1/tasks.get.ts': ROUTE });
  prepare(root, 'development', configured);
  expect(generated(root, 'config.ts')).toContain(
    `export const application = ${JSON.stringify(configured.application)} as const;`
  );
  expect(generated(root, 'config.ts')).toContain(
    'export const worker: WorkerOptions<Env> = {"http":{"basePath":"/api","healthPath":"/health"}};'
  );
  expect(generated(root, 'env.d.ts')).toContain(
    `InferEnv<\n  { env: {"TASKS":{"type":"kv"}} } | { env: {"TASKS":{"type":"kv"},"DEVELOPMENT_TOKEN":{"type":"secret"}} }\n>`
  );
  expect(generated(root, 'env.d.ts')).toContain('interface Env extends Cloudflare.Env {}');
  expect(generated(root, 'base.ts')).toContain(
    'const configured = maximus<Env>({ ...application, errors: standardErrors });'
  );
  expect(generated(root, 'base.ts')).toContain(
    'export const base = useProjectMiddleware(configured, middleware);'
  );
  expect(generated(root, 'register.d.ts')).toContain(
    'declare global {\n  interface MaximusRegister {\n    base: typeof base;\n    env: Env;\n  }\n}'
  );
  expect(generated(root, 'worker.ts')).toContain("import { worker as options } from './config.ts';");
  expect(generated(root, 'worker.ts')).toContain('WorkerRuntime<Env, typeof app.operations>');
  expect(generated(root, 'entry.ts')).toContain("export { default } from './worker.ts';");
});

test('errors.ts, auth.ts and context.ts complete the application, and none may import what is generated from it', () => {
  const root = project({
    'errors.ts': 'throw new Error("must not execute"); export default {};',
    'auth.ts': 'export default {};',
    'context.ts': 'export default {};',
  });
  prepare(root);
  const base = generated(root, 'base.ts');
  expect(base).toContain("import { defineAuth, maximus } from '@arbol-ai/maximus';");
  expect(base).toContain("import { bindContext, useProjectMiddleware } from '@arbol-ai/maximus/config';");
  expect(base).toContain(
    'const configured = maximus<Env>({ ...application, tokens: { ...application.tokens, ...defineAuth(auth) }, errors });'
  );
  expect(base).toContain(
    'export const base = useProjectMiddleware(bindContext(configured, context), middleware);'
  );
  const registration = generated(root, 'register.d.ts');
  expect(registration).toContain('import type errors from "../errors.ts";');
  expect(registration).toContain('    errors: typeof errors;');
  write(root, { 'errors.mjs': 'export default {};' });
  expect(() => prepare(root)).toThrow('Keep at most one errors module: errors.ts or errors.mjs.');
  for (const name of ['errors', 'auth', 'context']) {
    const cycle = project({
      [`${name}.ts`]: "import { base } from './.maximus/base.ts'; export default base;",
    });
    expect(() => prepare(cycle), name).toThrow('generated-module cycle');
  }
});

test("a cron module's literal schedule is reported for its trigger, and a computed one is not", () => {
  const root = project({
    'crons/daily.ts': "export const cron = '0 8 * * *'; export default () => {};",
    'crons/hourly.ts': "const every = '0 * * * *'; export const cron = every; export default () => {};",
  });
  expect(prepare(root).crons).toEqual([
    { file: join(root, 'crons/daily.ts'), cron: '0 8 * * *' },
    { file: join(root, 'crons/hourly.ts'), cron: undefined },
  ]);
  expect(generated(root, 'worker.ts')).toContain(
    'crons: [{ cron: schedule_0, handler: cron_0 }, { cron: schedule_1, handler: cron_1 }],'
  );
});

