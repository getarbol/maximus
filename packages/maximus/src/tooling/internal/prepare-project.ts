/**
 * `maximus prepare`: turns a project's files and what its `vite.config.ts` states into the modules of
 * `.maximus/`, which the Worker and the type checker load. Discovery parses application modules and never
 * runs them, so preparing a project executes none of its code and keeps filesystem code out of the Worker.
 */
import { existsSync, lstatSync, mkdirSync, readFileSync, renameSync, rmSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';

import type { ApplicationConfiguration } from '../../builder.ts';
import { ownsPrefix, VERSIONED_PATH } from '../../internal/http-layout.ts';
import { checkPagePaths } from '../../project/pages.ts';
import type { TokenPolicy } from '../../tokens.ts';
import { cronExpression, declarationExports, readProjectModule } from './project-exports.ts';
import { PROJECT_DIRECTORIES, projectFiles, projectPath, publicFiles, routeShape } from './project-files.ts';
import type { ProjectFile } from './project-files.ts';
import { mcpMarkdown } from './project-markdown.ts';

/**
 * What `vite.config.ts` configures, as the Vite plugin derives it: the application besides its code, the
 * Worker's HTTP paths and the bindings of each mode. Every value is plain data, which the generated modules
 * carry; the code that completes the application is `errors.ts`, `auth.ts` and `context.ts`.
 */
export interface ProjectOptions {
  /** Identity, origin, token policy, RPC callers and limits. */
  application: Omit<
    ApplicationConfiguration<unknown>,
    'errors' | 'tokens' | 'telemetry' | 'mcp' | 'rateLimit'
  > & {
    tokens: Omit<TokenPolicy, 'resolve' | 'resources' | 'resourceMetadataUrl'>;
    /** The rate limiting binding's name, which the generated application checks against `Env`. */
    rateLimit?: { binding: string; retryAfter?: number };
  };
  /**
   * The API's base path and the health path the Worker serves, and, for a web app (`index.html` at the
   * project's root), the static assets binding its build is served through and the headers of its responses.
   */
  worker: {
    http: { basePath: string; healthPath: string };
    assets?: { binding: string; headers?: Readonly<Record<string, string>> };
  };
  /** The bindings each mode declares, as `cf/config` states them: the generated `Env` is inferred from them. */
  env: { production: Readonly<Record<string, unknown>>; development: Readonly<Record<string, unknown>> };
}

/** What preparing a project found, for the plugin that reconfigures the Worker when it changes. */
export interface PreparedProject {
  /** The project's root. */
  directory: string;
  /** The mode the modules were prepared for: it selects `.dev` and `.prod` modules. */
  mode: string;
  /** Whether any generated module changed. */
  changed: boolean;
  /** The Durable Object modules, whose classes the Worker exports. */
  durableObjects: string[];
  /** Each cron module and the schedule it states as a literal, which becomes the Worker's trigger. */
  crons: { file: string; cron: string | undefined }[];
  /** The queues the queue modules consume, by their files' names: the Worker's consumer triggers. */
  queues: string[];
  /** Whether the project is a web app, whose Worker serves its build through the assets binding. */
  webApp: boolean;
  /** Every module and page discovery read, which the plugin watches. */
  files: string[];
  /** How many modules each convention holds. */
  modules: Record<string, number>;
}

/** The modules a generated one imports, each under a stable identifier. */
class Imports {
  readonly #lines: string[] = [];
  readonly #output: string;

  constructor(output: string) {
    this.#output = output;
  }

  /** The specifier that imports `file` from `.maximus/`. */
  source(file: string): string {
    return JSON.stringify(relative(this.#output, file).split(sep).join('/'));
  }

  /** Imports `file`'s default export as `identifier`, or the clause given. */
  add(identifier: string, file: string): string {
    this.#lines.push(`import ${identifier} from ${this.source(file)};`);
    return identifier;
  }

  get lines(): readonly string[] {
    return this.#lines;
  }
}

/** A generated module: the header that marks it, its imports and its statements. */
function generatedModule(mode: string, imports: readonly string[], body: readonly string[]): string {
  const header = `// Generated by maximus prepare (${mode}). Edit the source modules, not this file.`;
  return [header, ...imports, ...(imports.length ? [''] : []), ...body, ''].join('\n');
}

/**
 * The one module of a convention (`errors`, `app/root`, …), in any of its extensions, if any.
 */
function rootModule(root: string, name: string, extensions = ['ts', 'mts', 'js', 'mjs']): string | undefined {
  const found = extensions
    .map((extension) => `${name}.${extension}`)
    .filter((file) => existsSync(join(root, file)));
  if (found.length > 1) {
    throw new TypeError(`Keep at most one ${name} module: ${found.join(' or ')}.`);
  }
  const [module] = found;
  if (module && lstatSync(join(root, module)).isSymbolicLink()) {
    throw new TypeError(`The ${name} module cannot be a symlink.`);
  }
  return module;
}

/** The specifier `.maximus/` imports a root module by. */
function relativeModule(module: string): string {
  return JSON.stringify(`../${module}`);
}

/** A route's HTTP method, from its file's suffix: `index.get.ts` answers GET. */
const ROUTE_METHOD = /\.(get|post|put|patch|delete)$/;

/**
 * The routes `routes/` declares: one `defineHandler` per file, its path and method from the file's name, so
 * `routes/v1/tasks/[taskId].get.ts` answers `GET /v1/tasks/{taskId}`. Returns the mounts and whether any
 * route is also an MCP tool.
 */
function discoverRoutes(root: string, files: readonly ProjectFile[], imports: Imports) {
  const owners = new Map<string, string>();
  let mcp = false;
  const mounts = files.map(({ name, file }, index) => {
    const suffix = ROUTE_METHOD.exec(name);
    if (!suffix?.[1]) {
      throw new TypeError(
        `Name a route file by its method, such as routes/v1/tasks/index.get.ts: ${relative(root, file)}`
      );
    }
    const method = suffix[1].toUpperCase();
    const path = projectPath(name.slice(0, -suffix[0].length), 'routes');
    // `{taskId}` and `{id}` match the same paths.
    const claim = `${method} ${routeShape(path)}`;
    const owner = owners.get(claim);
    if (owner) {
      throw new TypeError(
        `Multiple route files claim ${method} ${path}: ${relative(root, owner)} and ${relative(root, file)}.`
      );
    }
    owners.set(claim, file);
    mcp = declarationExports(file, 'defineHandler').mcp || mcp;
    const identifier = imports.add(`route_${index}`, file);
    return `.mount(bindRoute(base, ${identifier}, ${JSON.stringify(path)}, ${JSON.stringify(method)}))`;
  });
  return { mounts, mcp };
}

/** The tools only MCP serves: each a top-level module of `mcp/tools/`, named by its file. */
function discoverTools(root: string, files: readonly ProjectFile[], imports: Imports): string[] {
  return files.map(({ name, file }, index) => {
    const tool = /^tools\/([a-z][a-z0-9]*(?:-[a-z0-9]+)*)$/.exec(name)?.[1];
    if (!tool) {
      throw new TypeError(
        `MCP modules are kebab-case tools directly in mcp/tools/, such as mcp/tools/summarize-tasks.ts: ${relative(root, file)}`
      );
    }
    declarationExports(file, 'defineTool');
    const identifier = imports.add(`tool_${index}`, file);
    return `.mount(bindTool(base, ${identifier}, ${JSON.stringify(tool)}))`;
  });
}

/**
 * The pages `pages/` declares: native responses at fixed paths outside the API, refused at a path the generated
 * Worker answers otherwise, as it would refuse them when it starts.
 */
function discoverPages(
  files: readonly ProjectFile[],
  imports: Imports,
  project: ProjectOptions,
  mcp: boolean
) {
  const paths = new Set<string>();
  const entries = files.map(({ name, file }, index) => {
    const path = projectPath(name, 'pages');
    if (paths.has(path)) {
      throw new TypeError(`Multiple page files claim ${path}.`);
    }
    paths.add(path);
    return `${JSON.stringify(path)}: ${imports.add(`page_${index}`, file)}`;
  });
  // The generated Worker answers the API, its own paths and, when it mounts mcp(), MCP at /mcp.
  checkPagePaths(paths, project.application.tokens, {
    http: project.worker.http,
    transports: mcp ? [{ path: '/mcp' }] : [],
  });
  return { paths, entries };
}

/** The queue consumers or email recipients a folder declares, each a top-level module named after its key. */
function discoverEvents(kind: 'queues' | 'email', files: readonly ProjectFile[], imports: Imports) {
  const keys = new Set<string>();
  return files.map(({ name, file }, index) => {
    if (name.includes('/') || keys.has(name)) {
      throw new TypeError(`${kind} modules require distinct top-level names: ${name}`);
    }
    keys.add(name);
    return `${JSON.stringify(name)}: ${imports.add(`${kind === 'queues' ? 'queue' : 'email'}_${index}`, file)}`;
  });
}

/** The name a Durable Object module's class is exported under: `session-store.ts` exports `SessionStore`. */
function durableObjectClass(name: string): string {
  return name
    .split('-')
    .map((part) => part[0]?.toUpperCase() + part.slice(1))
    .join('');
}

/**
 * Each binding to one of the Worker's own Durable Object classes, in every mode, as the namespace of that
 * class. Cloudflare's inference sees the Worker only by its name there, and types the namespace without it.
 */
function durableObjectBindings(
  project: ProjectOptions,
  files: readonly ProjectFile[],
  imports: Imports
): string[] {
  const classes = new Map(files.map(({ name, file }) => [durableObjectClass(name), imports.source(file)]));
  const { production, development } = project.env;
  return Object.entries(production).flatMap(([key, binding]) => {
    if (typeof binding !== 'object' || binding === null || !Object.hasOwn(development, key)) {
      return [];
    }
    const { type, worker, exportName } = binding as Record<string, unknown>;
    const source = typeof exportName === 'string' ? classes.get(exportName) : undefined;
    return type === 'durable-object' && worker === project.application.name && source
      ? [`  ${JSON.stringify(key)}: DurableObjectNamespace<import(${source}).default>;`]
      : [];
  });
}

/** The Durable Object classes `durable-objects/` declares, exported under the PascalCase of their files. */
function discoverDurableObjects(files: readonly ProjectFile[], imports: Imports): string[] {
  const classes = new Set(['Service']);
  return files.map(({ name, file }, index) => {
    if (!/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name)) {
      throw new TypeError(`Durable Object filenames must be top-level kebab-case names: ${name}`);
    }
    const className = durableObjectClass(name);
    if (classes.has(className)) {
      throw new TypeError(`Duplicate Worker export: ${className}`);
    }
    classes.add(className);
    return `export const ${className} = worker.durableObject(${imports.add(`durable_object_${index}`, file)});`;
  });
}

/**
 * A web app: `index.html` at the root, which the plugin found, and the pages `app/routes/` declares. The same
 * files make React Router's routes and the paths the Worker answers with the app's shell.
 */
function discoverWebApp(
  root: string,
  output: string,
  mode: string,
  project: ProjectOptions,
  pagePaths: ReadonlySet<string>
) {
  const web = project.worker.assets;
  if (!web) {
    if (existsSync(join(root, 'app/routes'))) {
      throw new TypeError(
        'app/routes/ holds the pages of a web app: add its index.html at the project root.'
      );
    }
    return undefined;
  }
  if (existsSync(join(root, 'app')) && lstatSync(join(root, 'app')).isSymbolicLink()) {
    throw new TypeError('Project directory cannot be a symlink: app');
  }
  const { basePath, healthPath } = project.worker.http;
  if (basePath === '' || basePath === '/') {
    throw new TypeError('A web app answers at the root: keep the API below http.basePath, /api by default.');
  }
  const layout = rootModule(root, 'app/root', ['tsx', 'jsx', 'ts', 'js']);
  const pages = projectFiles(root, 'app/routes', mode);
  // Without app/routes/, index.html is the one page, at the root.
  const shell = { paths: pages.length ? [] : ['/'], patterns: [] as string[] };
  const claimed = new Map<string, string>();
  const imports = new Imports(output);
  const routes = pages.map(({ name, file }) => {
    const route = projectPath(name, 'app');
    // `:taskId` and `:id` match the same paths.
    const shape = route.replaceAll(/:[^/]+/g, ':');
    const owner = claimed.get(shape);
    if (owner) {
      throw new TypeError(
        `Multiple page files claim ${route}: ${relative(root, owner)} and ${relative(root, file)}.`
      );
    }
    claimed.set(shape, file);
    if (route.includes(':')) {
      shell.patterns.push(`/^${route.replaceAll(/:[^/]+/g, '[^/]+').replaceAll('/', String.raw`\/`)}$/`);
    } else {
      shell.paths.push(route);
    }
    return `{ path: ${JSON.stringify(route)}, caseSensitive: true, lazy: () => import(${imports.source(file)}).then(page) }`;
  });
  for (const route of [...shell.paths, ...pages.map(({ name }) => projectPath(name, 'app'))]) {
    if (
      [basePath, '/.well-known', '/mcp', '/assets'].some((prefix) => ownsPrefix(prefix, route)) ||
      route === healthPath ||
      VERSIONED_PATH.test(route) ||
      pagePaths.has(route)
    ) {
      throw new TypeError(
        `The page ${route} claims a path the API, discovery, MCP, the build's assets or pages/ answer: move it in app/routes/.`
      );
    }
  }
  const source = pages.length
    ? generatedModule(
        mode,
        [
          "import type { ComponentType } from 'react';",
          "import type { RouteObject } from 'react-router';",
          ...(layout ? [`import * as layout from ${imports.source(join(root, layout))};`] : []),
        ],
        [
          '/** A page module: its default export renders the page, and its other exports are React Router’s. */',
          'function page<Module extends { default: ComponentType }>({ default: Component, ...route }: Module) {',
          '  return { ...route, Component };',
          '}',
          '',
          '/** The pages app/routes/ declares, each loaded when it is first visited. */',
          `export const routes: RouteObject[] = ${
            layout
              ? `[{ ...page(layout), children: [\n  ${routes.join(',\n  ')},\n] }]`
              : `[\n  ${routes.join(',\n  ')},\n]`
          };`,
        ]
      )
    : undefined;
  // The build's shell for the pages, public/ by name, the hashed /assets/ for good, and in development,
  // Vite's modules through the binding; a production build forwards nothing else.
  const policy = [
    `binding: ${JSON.stringify(web.binding)}`,
    ...(web.headers && Object.keys(web.headers).length ? [`headers: ${JSON.stringify(web.headers)}`] : []),
    `pages: { paths: ${JSON.stringify(shell.paths)}, patterns: [${shell.patterns.join(', ')}] }`,
    `files: ${JSON.stringify(publicFiles(root))}`,
    "immutablePrefixes: ['/assets']",
    `development: ${mode === 'development'}`,
  ];
  return {
    policy: `{ ${policy.join(', ')} }`,
    routes: source,
    files: [...pages.map(({ file }) => file), ...(layout ? [join(root, layout)] : [])],
    pages: pages.length,
  };
}

/**
 * Writes the generated modules, replacing only those whose text changed, and removes the ones whose sources
 * are gone. Every destination is checked before any is replaced, so a refusal keeps the previous output.
 */
function writeGenerated(
  output: string,
  generated: Readonly<Record<string, string>>,
  owned: readonly string[]
) {
  const stale = owned.filter((name) => !(name in generated) && existsSync(join(output, name)));
  for (const name of [...Object.keys(generated), ...stale]) {
    const target = join(output, name);
    if (existsSync(target) && (lstatSync(target).isSymbolicLink() || !lstatSync(target).isFile())) {
      throw new TypeError(`Generated files must be ordinary files: ${name}`);
    }
  }
  mkdirSync(output, { recursive: true });
  let changed = false;
  for (const [name, content] of Object.entries(generated)) {
    const target = join(output, name);
    if (!existsSync(target) || readFileSync(target, 'utf-8') !== content) {
      changed = true;
      const temporary = `${target}.${process.pid}.tmp`;
      writeFileSync(temporary, content, { flag: 'wx' });
      renameSync(temporary, target);
    }
  }
  for (const name of stale) {
    rmSync(join(output, name));
    changed = true;
  }
  return changed;
}

/**
 * Prepares the project at `directory` for a mode, `development` under `vp dev` and `production` for every
 * build: discovers its modules, refuses what would build a Worker other than the one its files describe, and
 * writes `.maximus/`. A refusal never replaces the previous output.
 */
export function prepareProject(directory: string, mode: string, project: ProjectOptions): PreparedProject {
  const root = resolve(directory);
  const output = join(root, '.maximus');
  if (existsSync(output) && lstatSync(output).isSymbolicLink()) {
    throw new TypeError('The generated .maximus directory cannot be a symlink.');
  }
  // The modules that complete the application vite.config.ts configures, each optional.
  const catalog = rootModule(root, 'errors');
  const auth = rootModule(root, 'auth');
  const context = rootModule(root, 'context');
  for (const module of [catalog, auth, context]) {
    if (module) {
      readProjectModule(join(root, module), 'config');
    }
  }
  const files = Object.fromEntries(
    PROJECT_DIRECTORIES.map((name) => [name, projectFiles(root, name, mode)])
  ) as Record<(typeof PROJECT_DIRECTORIES)[number], ProjectFile[]>;
  for (const { file } of files.middleware) {
    readProjectModule(file, 'middleware');
  }
  // The modules only the generated Worker imports, which may use the application but not the Worker.
  for (const { file } of [...files.pages, ...files.queues, ...files.email, ...files['durable-objects']]) {
    readProjectModule(file, 'worker');
  }
  // Each cron module's schedule, when it states it as a literal: the Worker's triggers.
  const schedules = files.crons.map(({ file }) => ({ file, cron: cronExpression(file) }));
  // What mcp/ describes of the MCP server in Markdown.
  const described = mcpMarkdown(root);

  const application = new Imports(output);
  const routes = discoverRoutes(root, files.routes, application);
  const tools = discoverTools(root, files.mcp, application);
  // A route or a tool that MCP serves, or Markdown that describes the server, needs the MCP transport.
  const servesMcp = routes.mcp || tools.length > 0 || described !== undefined;
  const binders = [
    ...(files.routes.length ? ['bindRoute'] : []),
    ...(tools.length ? ['bindTool'] : []),
    'checkProjectPipeline',
  ];

  const middleware = new Imports(output);
  const middlewareModules = files.middleware.map(({ file }, index) =>
    middleware.add(`middleware_${index}`, file)
  );

  const worker = new Imports(output);
  const pages = discoverPages(files.pages, worker, project, servesMcp);
  const crons = files.crons.map(({ file }, index) => {
    worker.add(`cron_${index}, { cron as schedule_${index} }`, file);
    return `{ cron: schedule_${index}, handler: cron_${index} }`;
  });
  const queues = discoverEvents('queues', files.queues, worker);
  const email = discoverEvents('email', files.email, worker);
  const durableObjects = discoverDurableObjects(files['durable-objects'], worker);
  const objects = durableObjectBindings(project, files['durable-objects'], new Imports(output));
  const web = discoverWebApp(root, output, mode, project, pages.paths);

  const generated: Record<string, string> = {
    // What vite.config.ts states, as data the Worker carries.
    'config.ts': generatedModule(
      mode,
      ["import type { WorkerOptions } from '@arbol-ai/maximus/workers';"],
      [
        `export const application = ${JSON.stringify(project.application)} as const;`,
        `export const worker: WorkerOptions<Env> = ${JSON.stringify({ http: project.worker.http })};`,
      ]
    ),
    // The bindings each mode declares, which Cloudflare's own inference turns into `Env`: a JSON value is
    // also its own literal type. A binding to one of the Worker's own Durable Object classes is typed by it.
    'env.d.ts': generatedModule(
      mode,
      [],
      [
        "type Bindings = import('cf/config').InferEnv<",
        `  { env: ${JSON.stringify(project.env.production)} } | { env: ${JSON.stringify(project.env.development)} }`,
        '>;',
        ...(objects.length ? ['type DurableObjects = {', ...objects, '};'] : []),
        '',
        'declare global {',
        '  namespace Cloudflare {',
        objects.length
          ? '    interface Env extends Omit<Bindings, keyof DurableObjects>, DurableObjects {}'
          : '    interface Env extends Bindings {}',
        '  }',
        '  interface Env extends Cloudflare.Env {}',
        '}',
        '',
        'export {};',
      ]
    ),
    'middleware.ts': generatedModule(
      mode,
      ["import { collectMiddleware } from '@arbol-ai/maximus/config';", ...middleware.lines],
      [
        `export const { middleware, requestMiddleware } = collectMiddleware([${middlewareModules.join(', ')}] as const);`,
      ]
    ),
    // The application vite.config.ts configures, completed by the optional errors, auth and context modules.
    // defineAuth again: whatever auth.ts exports, only its code joins the configured token policy.
    'base.ts': generatedModule(
      mode,
      [
        `import { ${[...(auth ? ['defineAuth'] : []), 'maximus', ...(catalog ? [] : ['standardErrors'])].join(', ')} } from '@arbol-ai/maximus';`,
        `import { ${context ? 'bindContext, ' : ''}useProjectMiddleware } from '@arbol-ai/maximus/config';`,
        "import { application } from './config.ts';",
        "import { middleware } from './middleware.ts';",
        ...(described ? ["import { mcp } from './mcp.ts';"] : []),
        ...(catalog ? [`import errors from ${relativeModule(catalog)};`] : []),
        ...(auth ? [`import auth from ${relativeModule(auth)};`] : []),
        ...(context ? [`import context from ${relativeModule(context)};`] : []),
      ],
      [
        `const configured = maximus<Env>({ ${[
          '...application',
          ...(auth ? ['tokens: { ...application.tokens, ...defineAuth(auth) }'] : []),
          catalog ? 'errors' : 'errors: standardErrors',
          ...(described ? ['mcp'] : []),
        ].join(', ')} });`,
        `export const base = useProjectMiddleware(${context ? 'bindContext(configured, context)' : 'configured'}, middleware);`,
      ]
    ),
    // The registry every declaration is typed by: the base's context, the error catalog and the bindings.
    'register.d.ts': generatedModule(
      mode,
      [
        "import type { base } from './base.ts';",
        ...(catalog ? [`import type errors from ${relativeModule(catalog)};`] : []),
      ],
      [
        'declare global {',
        '  interface MaximusRegister {',
        '    base: typeof base;',
        ...(catalog ? ['    errors: typeof errors;'] : []),
        '    env: Env;',
        '  }',
        '}',
      ]
    ),
    'app.ts': generatedModule(
      mode,
      [
        `import { ${binders.join(', ')} } from '@arbol-ai/maximus/config';`,
        "import { base } from './base.ts';",
        ...application.lines,
      ],
      [
        'export const app = checkProjectPipeline(',
        '  base,',
        `  base${[...routes.mounts, ...tools].map((mount) => `\n    ${mount}`).join('')}`,
        '    .build()',
        ');',
      ]
    ),
    'worker.ts': generatedModule(
      mode,
      [
        "import { createProjectWorker } from '@arbol-ai/maximus/project';",
        "import type { WorkerRuntime } from '@arbol-ai/maximus/workers';",
        ...(servesMcp ? ["import { mcp } from '@arbol-ai/maximus/mcp';"] : []),
        "import { app } from './app.ts';",
        "import { worker as options } from './config.ts';",
        "import { requestMiddleware } from './middleware.ts';",
        ...worker.lines,
      ],
      [
        'const worker: WorkerRuntime<Env, typeof app.operations> = createProjectWorker(',
        '  app,',
        '  {',
        `    pages: { ${pages.entries.join(', ')} },`,
        `    crons: [${crons.join(', ')}],`,
        `    queues: { ${queues.join(', ')} },`,
        `    email: { ${email.join(', ')} },`,
        '  },',
        '  {',
        '    ...options,',
        ...(servesMcp ? ['    transports: [mcp()],'] : []),
        ...(web ? [`    assets: ${web.policy},`] : []),
        '    http: { ...options.http, middleware: requestMiddleware },',
        '  }',
        ');',
        '',
        'export default worker.handler;',
        'export const Service = worker.entrypoint;',
        ...durableObjects,
      ]
    ),
    // The HTTP handler the Worker serves, without the Workers runtime: what a project's tests call in Node.
    'http.ts': generatedModule(
      mode,
      [
        "import { createHttpHandler } from '@arbol-ai/maximus';",
        ...(servesMcp ? ["import { mcp } from '@arbol-ai/maximus/mcp';"] : []),
        "import { app } from './app.ts';",
        "import { worker } from './config.ts';",
        "import { requestMiddleware } from './middleware.ts';",
      ],
      [
        '/** The API as the Worker serves it, below its base path and behind its middleware, for tests in Node. */',
        `export const handler = createHttpHandler(app, { ...worker.http, middleware: requestMiddleware${servesMcp ? ', transports: [mcp()]' : ''} });`,
      ]
    ),
    // The stable entry Cloudflare's plugin builds, whatever the Worker module exports.
    'entry.ts': generatedModule(
      mode,
      [],
      ["export { default } from './worker.ts';", "export * from './worker.ts';"]
    ),
    ...(web?.routes ? { 'app-routes.ts': web.routes } : {}),
    ...(described
      ? {
          'mcp.ts': generatedModule(
            mode,
            ["import type { McpConfiguration } from '@arbol-ai/maximus';"],
            [`export const mcp: McpConfiguration = ${JSON.stringify(described)};`]
          ),
        }
      : {}),
  };
  // Modules a generated one may leave behind once their sources are gone, and `routes.ts`, which earlier
  // releases generated.
  const changed = writeGenerated(output, generated, ['app-routes.ts', 'mcp.ts', 'routes.ts']);
  return {
    directory: root,
    mode,
    changed,
    durableObjects: files['durable-objects'].map(({ file }) => file),
    crons: schedules,
    queues: files.queues.map(({ name }) => name),
    webApp: web !== undefined,
    files: [
      ...Object.values(files)
        .flat()
        .map(({ file }) => file),
      ...(web?.files ?? []),
    ],
    modules: {
      ...Object.fromEntries(Object.entries(files).map(([kind, entries]) => [kind, entries.length])),
      app: web?.pages ?? 0,
    },
  };
}
